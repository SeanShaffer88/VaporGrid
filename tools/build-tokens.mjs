#!/usr/bin/env node
// Generates every token consumer from docs/tokens.json, the single source of truth.
//   node tools/build-tokens.mjs          write outputs
//   node tools/build-tokens.mjs --check  exit 1 if any output is missing or stale (CI)
// Zero dependencies. Outputs: demo/tokens.css and dist/* (DTCG JSON, XAML, Rust, Slint, GDScript).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'docs/tokens.json'), 'utf8'));
const revision = tokens.designRevision;
const generatedNote = `Generated by tools/build-tokens.mjs from docs/tokens.json (VaporGrid revision ${revision}). Do not edit.`;

const roles = Object.keys(tokens.color);
for (const theme of ['lightColor']) {
  const missing = roles.filter(role => !(role in tokens[theme]));
  if (missing.length) throw new Error(`${theme} is missing roles: ${missing.join(', ')}`);
}
const kebab = name => ({ background: 'bg', foreground: 'fg' })[name] ?? name.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`);
const pascal = name => name[0].toUpperCase() + name.slice(1);
const screaming = name => name.replace(/[A-Z]/g, c => `_${c}`).toUpperCase();
const snake = name => name.replace(/[A-Z]/g, c => `_${c.toLowerCase()}`);
const channels = hex => hex.slice(1).match(/../g).map(c => Number.parseInt(c, 16));
const fontStack = list => list.map(f => (/\s/.test(f) ? `'${f}'` : f)).join(', ');
const accentRoles = ['selectionIndicator', 'focus'];
const accentPresets = Object.entries(tokens.appearanceAccents.presets)
  .filter(([id]) => id !== tokens.appearanceAccents.default);
for (const [id, preset] of accentPresets) {
  if (!/^[a-z]+$/.test(id)) throw new Error(`Invalid accent ID: ${id}`);
  for (const theme of ['dark', 'light']) {
    for (const role of accentRoles) {
      if (!/^#[\da-f]{6}$/i.test(preset[theme]?.[role] ?? '') ||
          !/^oklch\([\d.]+ [\d.]+ [\d.]+\)$/.test(preset.oklch?.[theme]?.[role] ?? '')) {
        throw new Error(`Invalid ${id} ${theme} ${role} token`);
      }
    }
  }
}

// ---------- demo/tokens.css ----------
function css() {
  const block = (palette, indent, extra) => [
    ...roles.map(role => `${indent}--${kebab(role)}: ${palette[role]};`),
    ...extra.map(line => `${indent}${line}`),
  ].join('\n');
  const themeExtras = scheme => [`color-scheme: ${scheme};`, `--material-shadow: ${tokens.material[scheme].structuralShadow};`];
  const base = [
    `--font-body: ${fontStack(tokens.type.sans)};`,
    `--control-gap: ${tokens.space.controlGap}px;`,
    `--group-gap: ${tokens.space.relatedGroupGap[1]}px;`,
    `--section-gap: ${tokens.space.sectionGap}px;`,
    `--touch-target: ${tokens.density.touchControlMinWidth}px;`,
    `--motion-short: ${tokens.motion.shortTransition}ms;`,
    `--motion-panel: ${tokens.motion.panelTransition}ms;`,
    ...Object.entries(tokens.surfaceAliases).map(([alias, role]) => `--${alias}: var(--${kebab(role)});`),
  ];
  const scopes = (dark, light, indent) => [
    `${indent}:root {`,
    ...(indent ? [] : base.map(line => `  ${line}`)),
    block(dark, `${indent}  `, indent ? [] : themeExtras('dark')),
    `${indent}}`,
    `${indent}:root[data-theme=light] {`,
    block(light, `${indent}  `, indent ? [] : themeExtras('light')),
    `${indent}}`,
    `${indent}@media (prefers-color-scheme: light) {`,
    `${indent}  :root[data-theme=system] {`,
    block(light, `${indent}    `, indent ? [] : themeExtras('light')),
    `${indent}  }`,
    `${indent}}`,
  ].join('\n');
  function accentScopes(useOklch, indent = '') {
    return accentPresets.map(([id, preset]) => {
      const palette = useOklch ? preset.oklch : preset;
      const selector = `:root[data-accent=${id}]`;
      const declarations = theme => accentRoles.map(role => `--${kebab(role)}: ${palette[theme][role]};`).join(' ');
      return [
        `${indent}${selector} { ${declarations('dark')} }`,
        `${indent}${selector}[data-theme=light] { ${declarations('light')} }`,
        `${indent}@media (prefers-color-scheme: light) {`,
        `${indent}  ${selector}[data-theme=system] { ${declarations('light')} }`,
        `${indent}}`,
      ].join('\n');
    }).join('\n');
  }
  return [
    `/* ${generatedNote} */`,
    scopes(tokens.color, tokens.lightColor, ''),
    accentScopes(false),
    '',
    '@supports (color: oklch(0.5 0 0)) {',
    scopes(tokens.colorOklch.dark, tokens.colorOklch.light, '  '),
    accentScopes(true, '  '),
    '}',
    '',
    '@media (forced-colors: active) {',
    '  :root { --selection-indicator: Highlight !important; --focus: Highlight !important; }',
    '}',
    '',
  ].join('\n');
}

// ---------- dist/vaporgrid.tokens.json (W3C DTCG 2025.10 format) ----------
function dtcg() {
  const color = hex => ({ $type: 'color', $value: { colorSpace: 'srgb', components: channels(hex).map(c => +(c / 255).toFixed(6)), alpha: 1, hex: hex.toLowerCase() } });
  const dim = px => ({ $type: 'dimension', $value: { value: px, unit: 'px' } });
  const ms = value => ({ $type: 'duration', $value: { value, unit: 'ms' } });
  const palette = p => Object.fromEntries(roles.map(role => [role, color(p[role])]));
  const presets = Object.fromEntries(accentPresets.map(([id, preset]) => [id,
    Object.fromEntries(['dark', 'light'].map(theme => [theme,
      Object.fromEntries(accentRoles.map(role => [role, color(preset[theme][role])]))]))]));
  const d = tokens.density;
  return JSON.stringify({
    $description: generatedNote,
    color: { dark: palette(tokens.color), light: palette(tokens.lightColor), accentPresets: presets },
    space: {
      ...Object.fromEntries(tokens.space.scale.map(v => [`s${v}`, dim(v)])),
      controlGap: dim(tokens.space.controlGap), controlGapMinimum: dim(tokens.space.controlGapMinimum),
      relatedGroupGap: dim(tokens.space.relatedGroupGap[1]), sectionGap: dim(tokens.space.sectionGap),
      compartmentGutter: dim(tokens.space.compartmentGutter),
    },
    density: Object.fromEntries(['compact', 'comfortable', 'touch'].map(mode => [mode, {
      panelPadding: dim(d[mode].panelPadding), controlMinHeight: dim(d[mode].controlMinHeight),
    }])),
    touchTarget: dim(d.touchControlMinWidth),
    font: {
      sans: { $type: 'fontFamily', $value: tokens.type.sans },
      mono: { $type: 'fontFamily', $value: tokens.type.mono },
      size: Object.fromEntries(Object.entries(tokens.type.size).map(([k, v]) => [k, dim(v)])),
      weight: Object.fromEntries(Object.entries(tokens.type.weight).map(([k, v]) => [k, { $type: 'fontWeight', $value: v }])),
      lineHeight: { $type: 'number', $value: tokens.type.bodyLineHeight },
    },
    motion: { short: ms(tokens.motion.shortTransition), panel: ms(tokens.motion.panelTransition), maximum: ms(tokens.motion.maximumTransition) },
    inspector: { width: dim(tokens.compartments.inspectorWidth), min: dim(tokens.compartments.inspectorMin), max: dim(tokens.compartments.inspectorMax) },
  }, null, 2) + '\n';
}

// ---------- dist/VaporGrid.xaml (WinUI 3 / WPF ResourceDictionary) ----------
// High-contrast mapping keeps meaning while deferring to the user's Windows contrast theme.
const highContrast = {
  background: 'SystemColorWindowColor', surface: 'SystemColorWindowColor', raised: 'SystemColorWindowColor',
  selected: 'SystemColorHighlightColor', foreground: 'SystemColorWindowTextColor', muted: 'SystemColorWindowTextColor',
  border: 'SystemColorWindowTextColor', accent: 'SystemColorHighlightColor',
  accentForeground: 'SystemColorHighlightTextColor', selectionIndicator: 'SystemColorHighlightColor',
  focus: 'SystemColorHighlightColor',
  action: 'SystemColorButtonFaceColor', actionHover: 'SystemColorButtonFaceColor', actionPressed: 'SystemColorButtonFaceColor',
  progress: 'SystemColorHighlightColor', info: 'SystemColorWindowTextColor', warning: 'SystemColorWindowTextColor',
  success: 'SystemColorWindowTextColor', danger: 'SystemColorWindowTextColor',
  materialRim: 'SystemColorWindowTextColor', materialShade: 'SystemColorWindowColor',
};
function xamlThemes() {
  const dict = (key, body) => `      <ResourceDictionary x:Key="${key}">\n${body}\n      </ResourceDictionary>`;
  const colors = p => roles.map(role => `        <Color x:Key="Vg${pascal(role)}Color">${p[role]}</Color>`).join('\n');
  const hc = roles.map(role => `        <StaticResource x:Key="Vg${pascal(role)}Color" ResourceKey="${highContrast[role] ?? 'SystemColorWindowTextColor'}" />`).join('\n');
  const brushes = roles.map(role => `  <SolidColorBrush x:Key="Vg${pascal(role)}Brush" Color="{ThemeResource Vg${pascal(role)}Color}" />`).join('\n');
  return `<!-- ${generatedNote}
     WinUI 3: merge into Application.Resources. Default = dark signature; Light and HighContrast follow the system.
     WPF has no ThemeDictionaries: use VaporGrid.Dark.xaml / VaporGrid.Light.xaml instead. -->
<ResourceDictionary
    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <ResourceDictionary.ThemeDictionaries>
${dict('Default', colors(tokens.color))}
${dict('Light', colors(tokens.lightColor))}
${dict('HighContrast', hc)}
  </ResourceDictionary.ThemeDictionaries>
${brushes}
  <FontFamily x:Key="VgFontSans">${tokens.type.sans[0]}</FontFamily>
  <FontFamily x:Key="VgFontMono">${tokens.type.mono[0]}</FontFamily>
${Object.entries(tokens.type.size).map(([k, v]) => `  <x:Double x:Key="VgFontSize${pascal(k)}">${v}</x:Double>`).join('\n')}
  <Thickness x:Key="VgFocusVisualThickness">3</Thickness>
  <Thickness x:Key="VgFocusVisualMargin">-3</Thickness>
</ResourceDictionary>
`;
}
function xamlWpf(palette, scheme) {
  return `<!-- ${generatedNote}
     WPF ${scheme} palette. Swap this merged dictionary to change theme; use SystemColors when SystemParameters.HighContrast is true. -->
<ResourceDictionary
    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
    xmlns:sys="clr-namespace:System;assembly=mscorlib">
${roles.map(role => `  <Color x:Key="Vg${pascal(role)}Color">${palette[role]}</Color>\n  <SolidColorBrush x:Key="Vg${pascal(role)}Brush" Color="${palette[role]}" />`).join('\n')}
  <FontFamily x:Key="VgFontSans">${tokens.type.sans[0]}</FontFamily>
  <FontFamily x:Key="VgFontMono">${tokens.type.mono[0]}</FontFamily>
${Object.entries(tokens.type.size).map(([k, v]) => `  <sys:Double x:Key="VgFontSize${pascal(k)}">${v}</sys:Double>`).join('\n')}
</ResourceDictionary>
`;
}

// ---------- dist/vaporgrid.rs (no dependencies; wrap with egui::Color32::from_rgb etc.) ----------
function rust() {
  const field = role => `    pub ${snake(role)}: [u8; 3],`;
  const value = (p, role) => `    ${snake(role)}: [${channels(p[role]).map(c => `0x${c.toString(16).toUpperCase().padStart(2, '0')}`).join(', ')}],`;
  const s = tokens.space, d = tokens.density;
  return `// ${generatedNote}
//! VaporGrid design tokens. Colors are sRGB \`[r, g, b]\`; sizes are CSS-pixel equivalents (scale by DPI).
#![allow(dead_code)]

pub const DESIGN_REVISION: u32 = ${revision};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Palette {
${roles.map(field).join('\n')}
}

pub const DARK: Palette = Palette {
${roles.map(role => value(tokens.color, role)).join('\n')}
};

pub const LIGHT: Palette = Palette {
${roles.map(role => value(tokens.lightColor, role)).join('\n')}
};

pub const SPACE_SCALE: [f32; ${s.scale.length}] = [${s.scale.map(v => `${v}.0`).join(', ')}];
pub const CONTROL_GAP: f32 = ${s.controlGap}.0;
pub const CONTROL_GAP_MIN: f32 = ${s.controlGapMinimum}.0;
pub const GROUP_GAP: f32 = ${s.relatedGroupGap[1]}.0;
pub const SECTION_GAP: f32 = ${s.sectionGap}.0;
pub const TOUCH_TARGET: f32 = ${d.touchControlMinWidth}.0;

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Density { pub panel_padding: f32, pub control_min_height: f32 }
${['compact', 'comfortable', 'touch'].map(m => `pub const ${m.toUpperCase()}: Density = Density { panel_padding: ${d[m].panelPadding}.0, control_min_height: ${d[m].controlMinHeight}.0 };`).join('\n')}

pub const FONT_SANS: &[&str] = &[${tokens.type.sans.map(f => JSON.stringify(f)).join(', ')}];
pub const FONT_MONO: &[&str] = &[${tokens.type.mono.map(f => JSON.stringify(f)).join(', ')}];
${Object.entries(tokens.type.size).map(([k, v]) => `pub const FONT_SIZE_${k.toUpperCase()}: f32 = ${v}.0;`).join('\n')}
pub const LINE_HEIGHT: f32 = ${tokens.type.bodyLineHeight};
pub const FOCUS_OUTLINE: f32 = 3.0;
pub const FOCUS_OFFSET: f32 = 3.0;

pub const MOTION_SHORT_MS: u32 = ${tokens.motion.shortTransition};
pub const MOTION_PANEL_MS: u32 = ${tokens.motion.panelTransition};
pub const MOTION_MAX_MS: u32 = ${tokens.motion.maximumTransition};

pub const INSPECTOR_WIDTH: f32 = ${tokens.compartments.inspectorWidth}.0;
pub const INSPECTOR_MIN: f32 = ${tokens.compartments.inspectorMin}.0;
pub const INSPECTOR_MAX: f32 = ${tokens.compartments.inspectorMax}.0;
`;
}

// ---------- dist/VaporGrid.slint ----------
function slint() {
  return `// ${generatedNote}
// Bind \`VaporGrid.dark\` to the OS theme from Rust; high-contrast handling stays in the host.
export global VaporGrid {
    in-out property <bool> dark: true;
${roles.map(role => `    out property <color> ${kebab(role)}: dark ? ${tokens.color[role]} : ${tokens.lightColor[role]};`).join('\n')}
${Object.entries(tokens.surfaceAliases).map(([alias, role]) => `    out property <color> ${alias}: ${kebab(role)};`).join('\n')}
    out property <length> control-gap: ${tokens.space.controlGap}px;
    out property <length> group-gap: ${tokens.space.relatedGroupGap[1]}px;
    out property <length> section-gap: ${tokens.space.sectionGap}px;
    out property <length> touch-target: ${tokens.density.touchControlMinWidth}px;
${Object.entries(tokens.type.size).map(([k, v]) => `    out property <length> font-size-${k}: ${v}px;`).join('\n')}
    out property <string> font-sans: "${tokens.type.sans[0]}";
    out property <string> font-mono: "${tokens.type.mono[0]}";
    out property <duration> motion-short: ${tokens.motion.shortTransition}ms;
    out property <duration> motion-panel: ${tokens.motion.panelTransition}ms;
}
`;
}

// ---------- dist/vaporgrid_tokens.gd (Godot 4) ----------
function gdscript() {
  const col = hex => `Color(${channels(hex).map(c => +(c / 255).toFixed(6)).join(', ')})`;
  const dictionary = p => `{\n${roles.map(role => `\t"${snake(role)}": ${col(p[role])},`).join('\n')}\n}`;
  return `# ${generatedNote}
class_name VaporGridTokens
extends RefCounted

const DESIGN_REVISION := ${revision}
const DARK := ${dictionary(tokens.color)}
const LIGHT := ${dictionary(tokens.lightColor)}
const CONTROL_GAP := ${tokens.space.controlGap}
const SECTION_GAP := ${tokens.space.sectionGap}
const TOUCH_TARGET := ${tokens.density.touchControlMinWidth}
${Object.entries(tokens.type.size).map(([k, v]) => `const FONT_SIZE_${k.toUpperCase()} := ${v}`).join('\n')}
`;
}

const outputs = {
  'demo/tokens.css': css(),
  'dist/vaporgrid.tokens.json': dtcg(),
  'dist/VaporGrid.xaml': xamlThemes(),
  'dist/VaporGrid.Dark.xaml': xamlWpf(tokens.color, 'dark'),
  'dist/VaporGrid.Light.xaml': xamlWpf(tokens.lightColor, 'light'),
  'dist/vaporgrid.rs': rust(),
  'dist/VaporGrid.slint': slint(),
  'dist/vaporgrid_tokens.gd': gdscript(),
};

const check = process.argv.includes('--check');
const stale = [];
for (const [path, content] of Object.entries(outputs)) {
  const file = join(root, path);
  const current = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
  if (current === content) continue;
  if (check) { stale.push(path); continue; }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log(`wrote ${relative(root, file)}`);
}
if (check && stale.length) {
  console.error(`Stale token outputs (run node tools/build-tokens.mjs): ${stale.join(', ')}`);
  process.exit(1);
}
if (check) console.log('Token outputs are current.');
